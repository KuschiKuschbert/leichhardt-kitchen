// Additive capability preparation is tested only on synthetic emulator data.
import assert from 'node:assert/strict';
import { initializeApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import { bootstrapAccess } from './access-bootstrap.mjs';
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '')) throw new Error('This check requires a local Firestore emulator.');
initializeApp({ projectId: 'demo-capability-bootstrap' });
const db = getFirestore(), pin = '000000', root = db.collection('kitchens').doc(pin), config = root.collection('config').doc('main');
await config.set({ headId: 'head', staffIds: ['head', 'staff', 'view', 'fn'], sousIds: ['head'], fnIds: ['fn'], fnOnlyIds: ['fn'],
  people: [{ id: 'head', name: 'Synthetic head', role: 'head' }, { id: 'staff', name: 'Synthetic staff', role: 'staff', add: true, tick: false, del: false },
    { id: 'view', name: 'Synthetic viewer', role: 'view', add: false, tick: false, del: false }, { id: 'fn', name: 'Synthetic coordinator', role: 'fnc', add: true, tick: true }] });
const initial = JSON.stringify((await config.get()).data()), batch = db.batch();
const synthetic = { v: 1, status: 'confirmed', date: '2026-11-09', name: 'Synthetic event', mode: 'all', lines: [{ rid: 'pizza', name: 'Pizza', unit: 'platter', qty: 1, u: [0] }], rounds: [{ at: 1794211200000 }] };
for (let i = 0; i < 82; i++) batch.set(root.collection('functions').doc('synthetic-' + String(i).padStart(3, '0')), synthetic);
await batch.commit();
await root.collection('functions').doc('synthetic-000').collection('hist').doc('0').set({ was: {}, at: 1 });
const preview = await bootstrapAccess(db, pin, { dryRun: true });
assert.equal(preview.bookingsScanned, 82); assert.equal(preview.functionBookings, 82); assert.equal(preview.capabilityLists, 3);
assert.equal(JSON.stringify((await config.get()).data()), initial); assert.equal((await root.collection('functions').doc('synthetic-000').get()).data().effects, undefined);
await assert.rejects(() => bootstrapAccess(db, pin, { verifyOnly: true }), /preparation is incomplete/);
const prepared = await bootstrapAccess(db, pin);
assert.equal(prepared.functionBookings, 82); assert.equal(prepared.bookingsScanned, 82);
assert.equal((await root.collection('functions').doc('synthetic-000').get()).data().v, 1);
assert.equal((await root.collection('functions').doc('synthetic-000').get()).data().effects.prep['fn-synthetic-000-pizza'].fn, 'synthetic-000');
assert.deepEqual((await root.collection('functions').doc('synthetic-000').collection('hist').doc('0').get()).data(), { was: {}, at: 1 });
assert.equal((await bootstrapAccess(db, pin, { verifyOnly: true })).functionBookings, 0);
const changedBooking = root.collection('functions').doc('synthetic-000');
await changedBooking.update({ name: 'Synthetic changed event', v: 2 });
const stale = (await changedBooking.get()).data();
await assert.rejects(() => bootstrapAccess(db, pin, { verifyOnly: true }), /incomplete or stale/);
assert.deepEqual((await changedBooking.get()).data(), stale, 'Read-only verification cannot repair or alter the current booking.');
assert.equal((await bootstrapAccess(db, pin, { dryRun: true })).functionBookings, 1);
assert.equal((await bootstrapAccess(db, pin)).functionBookings, 1);
assert.equal((await changedBooking.get()).data().v, 2);
assert.match((await changedBooking.get()).data().effects.order.text, /Synthetic changed event/);
assert.equal((await bootstrapAccess(db, pin, { verifyOnly: true })).functionBookings, 0);
let c = (await config.get()).data();
assert.deepEqual(c.addIds, ['head', 'staff']); assert.deepEqual(c.tickIds, ['head']); assert.deepEqual(c.delIds, ['head']);
const snapshot = JSON.stringify(c);
assert.equal((await bootstrapAccess(db, pin)).functionBookings, 0);
assert.equal(JSON.stringify((await config.get()).data()), snapshot);
await config.update({ people: c.people.map(p => ({ ...p, add: true, tick: true, del: true })) });
await bootstrapAccess(db, pin);
c = (await config.get()).data();
assert.deepEqual(c.addIds, ['head', 'staff']); assert.deepEqual(c.tickIds, ['head']); assert.deepEqual(c.delIds, ['head']);
const roster = (await root.collection('login').doc('roster').get()).data();
assert.equal(roster.addIds, undefined); assert.equal(roster.tickIds, undefined); assert.equal(roster.delIds, undefined);
await config.update({ addIds: 'invalid' });
await assert.rejects(() => bootstrapAccess(db, pin), /capability list is invalid/);
assert.deepEqual((await config.get()).data().tickIds, ['head']);
console.log('PASS capability preparation on the real emulator: read-only semantic preview/verification, 82 bookings across query pages, derived-only stale-body repair with preserved booking version/history, exact repeat, preserved approvals, minimal roster and invalid-list refusal');
process.exit(0);
