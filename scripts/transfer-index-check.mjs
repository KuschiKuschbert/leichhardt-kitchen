// Run on the Firestore emulator. No production credentials or data.
import assert from 'node:assert/strict';
import { initializeApp, deleteApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import { syncTransfers } from './transfer-index.mjs';
if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Use the Firestore emulator.');
const app = initializeApp({ projectId: 'demo-test' }, 'transfer-index-check');
const k = getFirestore(app).collection('kitchens').doc('transfer-index-test');
const source = k.collection('transfers').doc('2025-01-01').collection('lines').doc('old-loan');
const ledger = k.collection('transferOpen').doc('2025-01-01_old-loan');
await source.set({ text: 'Butter', amount: 2, unit: 'kg', deleted: false });
assert.equal((await source.parent.parent.get()).exists, false, 'parent document is intentionally absent');
assert.equal(await syncTransfers(k), 1);
assert.equal((await ledger.get()).data().open, true, 'old loans are included');
const first = (await ledger.get()).updateTime.toMillis();
await syncTransfers(k);
assert.equal((await ledger.get()).updateTime.toMillis(), first, 'retry is idempotent');
await source.update({ returned: true, returnedBy: 'Tester', returnedAt: 123 });
await syncTransfers(k);
assert.equal((await ledger.get()).data().open, false, 'returned loans stay closed');
assert.equal((await ledger.get()).data().record.returnedBy, 'Tester', 'return audit survives');
await source.update({ returned: false, deleted: true });
await syncTransfers(k);
assert.equal((await ledger.get()).data().open, false, 'removed loans stay closed');
await source.update({ deleted: false });
await syncTransfers(k);
assert.equal((await ledger.get()).data().open, true, 'restored loans reopen');
await source.delete(); await ledger.delete();
await deleteApp(app);
console.log('Transfer index: all checks passed.');
