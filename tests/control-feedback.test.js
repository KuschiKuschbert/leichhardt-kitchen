// Feedback must not move navigation targets, leave a cancelled press stuck, or animate with reduced motion.
const L = require('./lib');
const { R, ok } = L.results();
const style = (p, sel) => p.$eval(sel, e => {
  const s = getComputedStyle(e), r = e.getBoundingClientRect();
  return { rotate: s.rotate, scale: s.scale, translate: s.translate, shadow: s.boxShadow, bg: s.backgroundColor,
    animation: s.animationName, focus: e.matches(':focus-visible'), outline: s.outlineStyle, x: r.x, y: r.y, w: r.width, h: r.height };
});
const still = s => s.rotate === 'none' && s.scale === 'none' && s.translate === 'none';
(async () => {
  const b = await L.start();
  let p = await L.open(b, '#/recipes', { who: 'sam', width: 1440, wait: 1600 });
  const hat = '.wtop-who', icon = hat + ' > svg', nav = '.pnav a[href="#/prep"]';
  const before = await style(p, hat), navBefore = await style(p, nav);
  await p.hover(hat); await L.settle(p, 250);
  ok((await style(p, icon)).rotate === '-8deg', 'mouse: the chef hat tilts left on hover');
  const over = await style(p, hat);
  ok(over.x === before.x && over.y === before.y && over.w === before.w && over.h === before.h, 'mouse: the hat chip keeps its position and tap area');
  await p.mouse.down(); await L.settle(p, 180);
  ok((await style(p, icon)).rotate === '-12deg', 'mouse: a held press deepens the hat tilt');
  await p.mouse.move(5, 200); await p.mouse.up(); await L.settle(p, 250);
  ok(still(await style(p, icon)) && !await p.$('.wm'), 'mouse: dragging off cancels the click and releases the hat');
  await p.hover(nav); await L.settle(p, 250);
  const navOver = await style(p, nav);
  ok(navOver.shadow !== navBefore.shadow && navOver.x === navBefore.x && navOver.y === navBefore.y, 'desktop navigation: a warm highlight keeps the text chip steady');
  await p.click(nav); await L.settle(p, 350);
  ok(await p.$('.pnav a[href="#/prep"][aria-current="page"]'), 'desktop navigation: release opens Prep and marks it current');
  await p.click(hat); await L.settle(p, 250);
  await p.hover('.wm-set'); await L.settle(p, 250);
  ok((await style(p, '.wm-set > svg')).translate === '2px', 'menu: a hovered row nudges its icon');
  await p.keyboard.press('Escape'); await L.settle(p, 250);
  const focus = await style(p, hat);
  ok(!await p.$('.wm') && focus.focus && focus.outline !== 'none', 'keyboard: Escape closes the menu and restores a visible focus ring');
  await p.emulateMedia({ reducedMotion: 'reduce' });
  await p.hover(hat); await p.mouse.down(); await L.settle(p, 200);
  ok(still(await style(p, icon)) && still(await style(p, hat)), 'reduced motion: hover and hold have no tilt, shift or compression');
  await p.mouse.up(); await L.settle(p, 200);
  ok((await style(p, '.wm')).animation === 'none', 'reduced motion: the menu opens without movement');
  await p.click('.wm-set'); await L.settle(p, 300);
  await p.emulateMedia({ reducedMotion: 'no-preference' });
  const chosen = '.settings button[data-act="settext"][aria-pressed="true"]';
  const chosenBefore = await style(p, chosen);
  await p.hover(chosen); await L.settle(p, 250);
  ok((await style(p, chosen)).bg === chosenBefore.bg, 'selected chip: hover preserves the selected colour');
  await p.mouse.down(); await L.settle(p, 180);
  const chipHeld = await style(p, chosen);
  ok(chipHeld.scale === '0.97' && chipHeld.translate === '0px 1px', 'chips: a held press compresses and moves down slightly');
  await p.mouse.move(5, 200); await p.mouse.up(); await L.settle(p, 250);
  const chosenView = '.view-opt[aria-checked="true"]';
  const viewBefore = await style(p, chosenView);
  await p.hover(chosenView); await L.settle(p, 250);
  ok((await style(p, chosenView)).shadow === viewBefore.shadow, 'view choices: hover preserves the selected outline');
  const button = '.settings button[data-act="settext"][data-val="large"]';
  // Use an existing action button to check a disabled control cannot acquire the enabled press treatment.
  await p.$eval(button, e => { e.disabled = true; });
  const disabled = await style(p, button);
  const rect = await p.locator(button).boundingBox();
  await p.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2); await p.mouse.down(); await L.settle(p, 200);
  const held = await style(p, button);
  ok(still(held) && held.shadow === disabled.shadow && held.bg === disabled.bg, 'disabled: hover and press leave the disabled action unchanged');
  await p.mouse.up();
  ok(p.errors.length === 0, 'desktop controls: no page errors ' + p.errors.join(' | '));
  await p.context().close();

  p = await L.open(b, '#/recipes', { who: 'sam', touch: true, width: 390, wait: 1600 });
  const tab = '.tabbar a[href="#/prep"]', tabIcon = tab + ' > svg';
  const touch = await p.context().newCDPSession(p);
  await touch.send('Emulation.setDeviceMetricsOverride', { width: 390, height: 844, deviceScaleFactor: 1, mobile: true });
  const r = await p.locator(tab).boundingBox();
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: r.x + r.width / 2, y: r.y + r.height / 2 }] });
  await L.settle(p, 180);
  const touchHeld = await style(p, tabIcon);
  ok(touchHeld.rotate === '-12deg', 'touch: the navigation icon tilts while held');
  await touch.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] }); await L.settle(p, 250);
  ok(still(await style(p, tabIcon)) && await p.evaluate(() => location.hash) === '#/recipes', 'touch: a cancelled gesture clears the press without navigating');
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: r.x + r.width / 2, y: r.y + r.height / 2 }] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] }); await L.settle(p, 350);
  ok(await p.$('.tabbar a[href="#/prep"][aria-current="page"]'), 'touch: release opens the chosen page');
  ok(still(await style(p, tabIcon)), 'touch: release leaves no sticky hover tilt');
  await p.emulateMedia({ reducedMotion: 'reduce' });
  await p.tap(hat); await L.settle(p, 200);
  ok((await style(p, '.wm')).animation === 'none', 'touch with reduced motion: the chef menu opens without animation');
  ok(!(await L.overflow(p)) && p.errors.length === 0, 'phone controls: no sideways scroll or page errors ' + p.errors.join(' | '));
  await p.context().close();
  await b.close();
  L.report(R);
})();
