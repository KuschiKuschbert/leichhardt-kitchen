const L = require('./lib');
const { R, ok } = L.results();
(async () => {
  const b = await L.start();
  for (const width of [390, 768, 1280]) {
    const p = await L.open(b, '#/recipes', { width, wait: 1200 });
    const input = p.locator('#find');
    await input.fill('chicken'); await L.settle(p, 300);
    const before = await p.locator('#find').getAttribute('data-committed-query');
    await input.blur(); await input.focus();
    ok(await input.inputValue() === '' && before === 'chicken', width + ': refocus clears the draft while keeping the committed query');
    ok((await input.getAttribute('placeholder')).includes("Filtering by 'chicken'"), width + ': refocus explains the retained results');
    await input.fill('b'); await L.settle(p, 220);
    ok(await input.getAttribute('data-committed-query') === 'chicken', width + ': one character does not replace results');
    await input.blur(); ok(await input.inputValue() === 'chicken', width + ': accidental focus restores the previous query');
    await input.focus(); await input.fill('be'); await L.settle(p, 250);
    ok(await input.getAttribute('data-committed-query') === 'be', width + ': two characters commit the replacement');
    await input.locator('..').locator('.ux-search-clear').click();
    ok(await input.inputValue() === '' && await input.getAttribute('data-committed-query') === '', width + ': explicit reset clears draft and committed query');
    // Exercise the real compact choice control, not the hidden legacy chip.
    const group = p.locator('[data-act="kind"]').first().locator('..');
    await group.evaluate(el => el.nextElementSibling.click());
    await L.settle(p, 220);
    ok(await p.locator('.ux-picker').count() === 1 && await p.locator('.ux-picker input[type="search"]').count() === ((await group.locator('button').count()) > 12 ? 1 : 0), width + ': search visibility follows the choice threshold');
    const geometry = await p.locator('.ux-picker').evaluate(el => { const r = el.getBoundingClientRect(); return { bottom: r.bottom, top: r.top, height: innerHeight }; });
    ok(width < 768 ? Math.abs(geometry.bottom - geometry.height) < 2 : geometry.top > 0, width + ': responsive picker placement');
    await p.keyboard.press('ArrowDown'); await p.keyboard.press('Enter');
    ok(await p.locator('.ux-picker').count() === 0, width + ': keyboard selection commits and closes');
    await L.choose(p, '[data-act="amode"][data-val="free"]');
    await L.settle(p, 200);
    await p.locator('[data-act="free"]').first().evaluate(el => el.closest('.ux-choice-source').nextElementSibling.click());
    await p.locator('.ux-picker-option').nth(0).click(); await p.locator('.ux-picker-option').nth(1).click();
    await p.locator('.ux-picker-footer .dark').click();
    ok(await p.locator('[data-act="free"][aria-pressed="true"]').count() === 2, width + ': applying multiple recipe filters survives intervening app redraws');
    await L.settle(p, 200);
    await p.locator('[data-act="free"]').first().evaluate(el => el.closest('.ux-choice-source').nextElementSibling.click());
    await p.locator('.ux-picker-footer .btn').first().click(); await p.locator('.ux-picker-footer .dark').click();
    ok(await p.locator('[data-act="free"][aria-pressed="true"]').count() === 0, width + ': multi-select Clear applies to the real recipe filters');
    await p.evaluate(() => {
      const select = document.createElement('select'); select.id = 'ux-many'; select.setAttribute('aria-label', 'Many choices');
      for (let i = 0; i < 160; i++) select.add(new Option('Choice ' + i, String(i)));
      document.querySelector('#main').append(select); window.LK_UX.enhance(document);
    });
    await p.locator('#ux-many + .ux-picker-trigger').click();
    ok(await p.locator('.ux-picker input[type="search"]').count() === 1 && await p.locator('.ux-picker-option').count() <= 24, width + ': extended choices use search and window large lists');
    await p.locator('.ux-picker input').fill('Choice 149'); await p.locator('.ux-picker input').press('Enter');
    await p.locator('.ux-picker-option').click();
    ok(await p.locator('#ux-many').inputValue() === '149', width + ': a virtualised choice reaches the native form state');
    await p.evaluate(() => {
      const select = document.createElement('select'); select.id = 'ux-multi'; select.multiple = true; select.setAttribute('aria-label', 'Multi choices');
      ['First', 'Second', 'Third'].forEach(x => select.add(new Option(x, x))); document.querySelector('#main').append(select); window.LK_UX.enhance(document);
    });
    await p.locator('#ux-multi + .ux-picker-trigger').click();
    ok(await p.locator('.ux-picker input[type="search"]').count() === 0, width + ': compact multi-select omits search');
    await p.keyboard.press('Shift+Tab');
    ok(await p.evaluate(() => !!document.activeElement.closest('.ux-picker')), width + ': keyboard focus remains inside the modal');
    await p.locator('.ux-picker-option').nth(0).click(); await p.locator('.ux-picker-option').nth(1).click();
    ok(await p.locator('#ux-multi').evaluate(el => el.selectedOptions.length) === 0, width + ': multi-select edits remain a draft');
    await p.locator('.ux-picker-footer .dark').click();
    ok(await p.locator('#ux-multi').evaluate(el => el.selectedOptions.length) === 2, width + ': Apply commits the multi-select draft');
    await p.locator('#ux-multi + .ux-picker-trigger').click();
    await p.locator('.ux-picker-footer .btn').first().click(); await p.keyboard.press('Escape');
    ok(await p.locator('#ux-multi').evaluate(el => el.selectedOptions.length) === 2 && await p.evaluate(() => document.activeElement.id) === 'ux-multi-picker', width + ': cancelling Clear preserves selection and restores trigger focus');
    await L.settle(p, 200);
    await p.locator('#ux-multi + .ux-picker-trigger').click();
    await p.goBack(); await L.settle(p, 250);
    ok(await p.locator('.ux-picker').count() === 0 && await p.evaluate(() => location.hash) === '#/recipes', width + ': native Back closes the picker and keeps the page');
    if (width === 390) {
      await p.locator('#ux-multi + .ux-picker-trigger').click();
      const handle = await p.locator('.ux-picker-grip').boundingBox();
      await p.mouse.move(handle.x + handle.width / 2, handle.y + 5); await p.mouse.down(); await p.mouse.move(handle.x + handle.width / 2, handle.y + 90); await p.mouse.up();
      ok(await p.locator('.ux-picker').count() === 0, 'phone: dragging the handle down dismisses the sheet');
    }
    await L.settle(p, 200);
    await p.evaluate(() => {
      const form = document.createElement('form'); form.id = 'ux-validation';
      form.innerHTML = '<label>Required choice<select id="ux-required" required><option value="">Choose</option><option value="yes">Yes</option></select></label>';
      document.querySelector('#main').append(form); LK_UX.enhance(document); form.reportValidity();
    });
    ok(await p.locator('#ux-required-picker').getAttribute('aria-invalid') === 'true' && await p.locator('#ux-validation [role="alert"]').count() === 1, width + ': native validation reaches the visible trigger with an error message');
    await L.pick(p, '#ux-required', 'yes');
    ok(await p.locator('#ux-validation').evaluate(form => form.checkValidity()) && await p.locator('#ux-validation [role="alert"]').count() === 0, width + ': selecting a valid choice clears the native validation error');
    ok(!(await L.overflow(p)) && p.errors.length === 0, width + ': no overflow or browser errors ' + p.errors.join('|'));
    await p.context().close();
  }
  const p = await L.open(b, '#/admin', { admin: true, adminPage: 'people', width: 1280, wait: 1400 });
  await L.adminTab(p, 'people');
  const header = p.locator('[data-lv="people"] [data-p="lv-col"]').first();
  await header.click(); ok(await header.locator('..').getAttribute('aria-sort') === 'ascending', 'admin: header starts with ascending sort');
  await header.click(); ok(await header.locator('..').getAttribute('aria-sort') === 'descending', 'admin: second click descends');
  await header.click(); ok(await header.locator('..').getAttribute('aria-sort') === 'none', 'admin: third click restores the default order');
  const q = p.locator('[data-k="lv-q:people"]'); await q.fill('ann'); await L.settle(p, 240);
  ok(await p.locator('[data-lvb="people"] tbody tr').count() === 1, 'admin: search filters complete list');
  await p.locator('[data-lva="people"] [data-part="all"]').click();
  ok(await q.inputValue() === '' && await p.locator('[data-lvb="people"] tbody tr').count() === 4, 'admin: Reset All Filters restores all four people, including the signed-in head, and clears search');
  ok(p.errors.length === 0, 'admin: no browser errors ' + p.errors.join('|'));
  await p.context().close();
  const seed = L.seed(), configKey = ['kitchens', L.PIN, 'config', 'main'].join('/');
  for (let i = 22; i >= 1; i--) seed[configKey].people.push({ id: 'person-' + i, name: 'Person ' + String(i).padStart(2, '0'), role: 'staff', add: i % 2 === 0, tick: true, active: true });
  const many = await L.open(b, '#/admin', { admin: true, adminPage: 'people', width: 1280, extra: { [configKey]: seed[configKey] }, wait: 1200 });
  await L.adminTab(many, 'people');
  await many.locator('[data-lv="people"] [data-p="lv-col"]').first().click();
  const names = await many.locator('[data-lvb="people"] [data-a="name"]').evaluateAll(nodes => nodes.map(x => x.value));
  ok(names.includes('Person 01') && names.length === 15, 'admin: sorting runs over every record before the 15-row page limit');
  const roleFilter = many.locator('[data-k="lv-cf:people"]').first();
  const staffValue = await roleFilter.evaluate(el => [...el.options].find(o => /staff/i.test(o.textContent)).value);
  await L.pick(many, '[data-k="lv-cf:people"]', staffValue);
  ok(await many.locator('[data-lva="people"] [data-part^="facet:"]').count() === 1 && !(await many.locator('[data-lvb="people"] [data-a="name"]').evaluateAll(nodes => nodes.some(x => x.value === 'Sam'))), 'admin: a categorical column filter has a removable active badge');
  await many.locator('[data-k="lv-q:people"]').fill('No matching person'); await L.settle(many, 250);
  await many.locator('[data-p="lv-clear"][data-lv="people"]').click();
  ok(await many.locator('[data-lvb="people"] tbody tr').count() === 15 && await roleFilter.inputValue() === '', 'admin: the empty-state clear also resets categorical column filters');
  await many.locator('[data-lva="people"] [data-part="all"]').click();
  await many.evaluate(() => {
    const box = document.createElement('div'); box.innerHTML = '<div><table id="ux-report"><thead><tr><th>Number</th><th>Date</th><th>Status</th></tr></thead><tbody><tr><td>10</td><td><time data-sort-value="2026-12-31">31 Dec</time></td><td>Open</td></tr><tr><td>2</td><td><time data-sort-value="2027-01-01">1 Jan</time></td><td>Done</td></tr></tbody></table></div>'; document.querySelector('.p-admin').append(box); LK_UX.enhance(document);
  });
  await many.locator('#ux-report thead button').first().click();
  ok(await many.locator('#ux-report tbody tr').first().locator('td').first().textContent() === '2', 'reports: numeric sorting puts 2 before 10');
  await many.locator('#ux-report thead button').nth(1).click();
  ok(await many.locator('#ux-report tbody tr').first().locator('td').first().textContent() === '10', 'reports: timestamp sorting keeps December before the following January');
  ok(many.errors.length === 0, 'complete-list and report sorting have no browser errors ' + many.errors.join('|'));
  await many.context().close();
  await b.close(); L.report(R);
})().catch(e => { console.error(e); process.exit(1); });
